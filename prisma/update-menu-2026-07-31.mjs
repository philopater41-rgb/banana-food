async function getCategory(name) {
  return prisma.category.upsert({ where: { name }, update: { isActive: true }, create: { name, isActive: true } });
}

async function main() {
  let updated = 0;
  let added = 0;

  for (const [categoryName, oldName, name, price] of existingUpdates) {
    const item = await prisma.item.findFirst({ where: { name: oldName, category: { name: categoryName } } });
    if (!item) {
      console.warn(`Existing menu item was not found: ${categoryName} / ${oldName}`);
      continue;
    }
    await prisma.item.update({ where: { id: item.id }, data: { name, price, isActive: true } });
    updated += 1;
  }

  for (const [categoryName, items] of Object.entries(newMenuItems)) {
    const category = await getCategory(categoryName);
    for (const [name, price] of items) {
      const item = await prisma.item.findFirst({ where: { name, categoryId: category.id } });
      if (item) {
        await prisma.item.update({ where: { id: item.id }, data: { price, isActive: true } });
      } else {
        await prisma.item.create({ data: { name, price, categoryId: category.id, isActive: true } });
        added += 1;
      }
    }
  }

  console.log(`Menu update complete: ${updated} existing prices updated, ${added} new menu-only items added.`);
}

main()
  .catch((error) => { console.error(error); process.exit(1); })
  .finally(() => prisma.$disconnect());
